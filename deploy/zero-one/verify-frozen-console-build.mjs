#!/usr/bin/env node
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const repositoryRoot = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const targets = {
  'cn-provider-admin': 'vite.cn-provider-admin.config.ts',
  'online-image': 'vite.online-image.config.ts',
  'password-recovery': 'vite.password-recovery.config.mjs',
}

const target = process.argv[2]
const config = targets[target]
if (!config) {
  process.stderr.write(`usage: ${process.argv[1]} <${Object.keys(targets).join('|')}>\n`)
  process.exit(2)
}

const outputRoot = mkdtempSync(resolve(tmpdir(), `zero-one-${target}-`))

function filesBelow(root, relative = '') {
  return readdirSync(resolve(root, relative), { withFileTypes: true })
    .flatMap((entry) => {
      const path = relative ? `${relative}/${entry.name}` : entry.name
      return entry.isDirectory() ? filesBelow(root, path) : [path]
    })
    .sort()
}

function requireIdenticalTree(generatedRoot, checkedInRoot) {
  const generated = filesBelow(generatedRoot)
  const checkedIn = filesBelow(checkedInRoot)
  if (generated.join('\n') !== checkedIn.join('\n')) {
    throw new Error(`${target} generated file set differs from the checked-in immutable namespace`)
  }
  for (const path of generated) {
    if (!readFileSync(resolve(generatedRoot, path)).equals(readFileSync(resolve(checkedInRoot, path)))) {
      throw new Error(`${target} generated bytes differ from checked-in ${path}`)
    }
  }
}

try {
  const result = spawnSync(
    'pnpm',
    ['--dir', 'frontend', 'exec', 'vite', 'build', '--config', config],
    {
      cwd: repositoryRoot,
      env: { ...process.env, ZERO_ONE_FROZEN_BUILD_ROOT: outputRoot },
      stdio: 'inherit',
    },
  )
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
  if (target === 'cn-provider-admin') {
    requireIdenticalTree(
      resolve(outputRoot, 'cn-provider-admin-v10'),
      resolve(repositoryRoot, 'deploy/zero-one/recovered-frontend/console/assets/cn-provider-admin-v10'),
    )
  }
  const detail = target === 'cn-provider-admin'
    ? 'checked-in assets are byte-identical'
    : 'repository assets unchanged'
  process.stdout.write(`Frozen Console source compatibility OK (${target}); ${detail}\n`)
} finally {
  rmSync(outputRoot, { recursive: true, force: true })
}
